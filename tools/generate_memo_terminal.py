#!/usr/bin/env python3
"""Double Unscii-8 glyph rows, preserving its real 8 px horizontal advance."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "assets/fonts/source/lvgl_unscii_8.c"
OUTPUT = ROOT / "assets/fonts/memo_font_terminal.c"


def generate():
    source = SOURCE.read_text()
    assert hashlib.sha256(SOURCE.read_bytes()).hexdigest() == "bd95b245eaea139aa7c4d9efbc130cc8eda4c11dc7a22b42048a7f0d814e29bf", "Pinned font source changed"
    bitmap_match = re.search(r"(glyph_bitmap\[\] = \{)(.*?)(\n\};)", source, re.S)
    desc_match = re.search(r"(glyph_dsc\[\] = \{)(.*?)(\n\};)", source, re.S)
    bitmap = bytes(int(n, 16) for n in re.findall(r"0x([0-9a-fA-F]{2})", bitmap_match[2]))
    glyphs = re.findall(r"\{\.bitmap_index = (\d+), \.adv_w = (\d+), \.box_w = (\d+), "
                        r"\.box_h = (\d+), \.ofs_x = (-?\d+), \.ofs_y = (-?\d+)\}", desc_match[2])
    assert len(glyphs) == 97
    data, descriptors = bytearray(), []
    for number, values in enumerate(glyphs):
        index, advance, width, height, x, y = map(int, values)
        assert (number == 0 and advance == 0) or advance == 128
        assert width + x <= 8
        new_index, bits = len(data), []
        for row in range(height):
            pixels = [(bitmap[index + (row*width+col)//8] >> (7-(row*width+col)%8)) & 1
                      for col in range(width)]
            bits.extend(pixels + pixels)
        for offset in range(0, len(bits), 8):
            value = sum(bit << (7-i) for i, bit in enumerate(bits[offset:offset+8]))
            data.append(value)
        descriptors.append(f"    {{.bitmap_index = {new_index}, .adv_w = {advance}, "
                           f".box_w = {width}, .box_h = {height*2}, .ofs_x = {x}, .ofs_y = {y*2}}}")
    bitmap_text = "\n" + "\n".join("    " + ", ".join(f"0x{v:02x}" for v in data[i:i+16]) + ","
                                      for i in range(0, len(data), 16))
    result = source[:desc_match.start(2)] + "\n" + ",\n".join(descriptors) + source[desc_match.end(2):]
    result = result[:bitmap_match.start(2)] + bitmap_text + result[bitmap_match.end(2):]
    result = result.replace("lv_font_unscii_8", "memo_font_terminal")
    result = result.replace("LV_FONT_UNSCII_8", "MEMO_FONT_TERMINAL")
    result = result.replace(".line_height = 9,", ".line_height = 18,")
    digest = hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    return ("/* Generated by tools/generate_memo_terminal.py. 8 px advance, 18 px line.\n"
            " * Vertically doubled Unscii-8 from LVGL; horizontal pixels unchanged.\n"
            " * Copyright (c) 2025 LVGL Kft. MIT: LICENSE.lvgl.txt.\n"
            f" * Source SHA-256: {digest}\n */\n" + result)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = generate()
    if args.check:
        assert OUTPUT.read_text() == output, "Terminal font needs regeneration"
    else:
        OUTPUT.write_text(output)
    print("Terminal font reproduction: PASS")
